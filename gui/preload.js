const { contextBridge, ipcRenderer, webUtils } = require('electron');

// The renderer's only access to the main process; it has no Node APIs itself.
contextBridge.exposeInMainWorld('api', {
  info: () => ipcRenderer.invoke('app:info'),
  chooseRoot: () => ipcRenderer.invoke('app:choose-root'),
  pick: kind => ipcRenderer.invoke('dialog:pick', kind),
  start: input => ipcRenderer.invoke('run:start', input),
  stop: () => ipcRenderer.invoke('run:stop'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: values => ipcRenderer.invoke('settings:save', values),
  resetVideo: videoPath => ipcRenderer.invoke('video:reset', videoPath),
  open: target => ipcRenderer.invoke('shell:open', target),
  reveal: target => ipcRenderer.invoke('shell:reveal', target),
  openLogs: () => ipcRenderer.invoke('shell:open-logs'),
  checkDeps: () => ipcRenderer.invoke('deps:check'),
  testDep: which => ipcRenderer.invoke('deps:test', which),
  fetchModels: () => ipcRenderer.invoke('deps:models'),
  precheck: input => ipcRenderer.invoke('run:precheck', input),
  setSetting: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  llmProviders: () => ipcRenderer.invoke('llm:providers'),
  llmModels: overrides => ipcRenderer.invoke('llm:models', overrides),
  keyStatus: () => ipcRenderer.invoke('keys:status'),
  setKey: (name, value) => ipcRenderer.invoke('keys:set', name, value),
  runSetup: (checkId, optionIndex) => ipcRenderer.invoke('setup:run', checkId, optionIndex),
  runMissingSetup: () => ipcRenderer.invoke('setup:run-missing'),
  copy: text => ipcRenderer.invoke('clipboard:write', text),
  openExternal: url => ipcRenderer.invoke('shell:external', url),
  openTerminal: () => ipcRenderer.invoke('shell:terminal'),
  pathForFile: file => webUtils.getPathForFile(file),
  onPipeline: fn => ipcRenderer.on('pipeline', (_e, msg) => fn(msg)),
});
